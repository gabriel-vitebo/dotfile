#!/bin/bash
# No runtime, network, privilege escalation or personal dotfile imports.
set -eu
umask 077
fail() { printf 'Erro: %s\n' "$*" >&2; exit 1; }
confirm() {
    printf '%s [s/N] ' "$*"
    answer=
    IFS= read -r answer || return 1
    case "$answer" in s|S|sim|y|Y|yes) return 0 ;; *) return 1 ;; esac
}
case "$(uname -s)" in
    Linux) platform=Linux ;;
    Darwin) platform=macOS ;;
    *) fail 'Somente Linux e macOS são suportados.' ;;
esac
for command in bash dirname mkdir mktemp cp mv rm rmdir chmod cmp grep find cksum; do
    command -v "$command" >/dev/null 2>&1 || fail "Pré-requisito ausente: $command"
done
[ -n "${HOME:-}" ] && [ "${HOME#/}" != "$HOME" ] || fail 'HOME deve ser absoluto.'
root=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd -P)
[ ! -L "$root/bin" ] && [ ! -L "$root/lib" ] && [ ! -L "$root/modules" ] && [ ! -L "$root/platforms" ] && [ ! -L "$root/manifests" ] && [ ! -L "$root/manifests/terminal" ] || fail 'Diretórios de execução não podem ser links.'
# Explicit allowlist prevents copying inventories, dotfiles or credentials.
for file in bin/config-workplace lib/cli.sh lib/setup.sh modules/initial-dev.sh lib/dev-tools.sh lib/dev-safety.sh lib/pnpm-metadata.js lib/vscode.sh platforms/dev-install.sh lib/vscode-settings.js manifests/vscode-extensions.txt manifests/vscode-settings.json modules/terminal.sh lib/terminal-detect.sh lib/terminal-files.sh platforms/terminal-install.sh manifests/terminal/zshrc manifests/terminal/plugins.txt; do
    [ -f "$root/$file" ] && [ ! -L "$root/$file" ] || fail "Arquivo ausente ou link não permitido: $file"
    case "$file" in *.sh|bin/*) /bin/bash -n "$root/$file" || fail "Sintaxe inválida: $file" ;; esac
done
base="$HOME/.local"
target="$base/share/config-workplace"
entry="$base/bin/config-workplace"
mkdir -p "$base/share" "$base/bin" "$base/state/config-workplace"
# Serialize updates without requiring flock (not shipped with macOS).
lock="$base/share/.config-workplace-install.lock"
mkdir "$lock" 2>/dev/null || fail "Outra instalação em andamento (ou lock residual): $lock"
work=
old_saved=0
new_live=0
entry_saved=0
entry_live=0
committed=0
cleanup() {
    result=$?
    trap - EXIT HUP INT TERM
    if [ "$committed" -eq 0 ] && [ -n "$work" ]; then
        if [ "$entry_live" -eq 1 ]; then rm -f "$entry"; fi
        if [ "$entry_saved" -eq 1 ]; then mv "$work/previous-entry" "$entry" || result=1; fi
        if [ "$new_live" -eq 1 ]; then rm -rf "$target"; fi
        if [ "$old_saved" -eq 1 ]; then mv "$work/previous" "$target" || result=1; fi
    fi
    # Keep recovery artifacts if restoration itself failed.
    if [ -n "$work" ]; then
        if [ "$committed" -eq 0 ] && { [ -e "$work/previous" ] || [ -e "$work/previous-entry" ] || [ -L "$work/previous-entry" ]; }; then
            printf 'Backup para recuperação manual: %s\n' "$work" >&2
        else
            rm -rf "$work"
        fi
    fi
    rmdir "$lock" || true
    exit "$result"
}
trap cleanup EXIT
trap 'exit 130' INT
trap 'exit 143' HUP TERM
work=$(mktemp -d "$base/share/.config-workplace.XXXXXX")
mkdir -p "$work/new/bin" "$work/new/lib" "$work/new/modules" "$work/new/platforms" "$work/new/manifests/terminal"
for file in bin/config-workplace lib/cli.sh lib/setup.sh modules/initial-dev.sh lib/dev-tools.sh lib/dev-safety.sh lib/pnpm-metadata.js lib/vscode.sh platforms/dev-install.sh lib/vscode-settings.js manifests/vscode-extensions.txt manifests/vscode-settings.json modules/terminal.sh lib/terminal-detect.sh lib/terminal-files.sh platforms/terminal-install.sh manifests/terminal/zshrc manifests/terminal/plugins.txt; do cp "$root/$file" "$work/new/$file"; done
chmod 755 "$work/new/bin/config-workplace"
# Recognize only the exact payload generated by this bootstrap.
printf '%s\n' 'config-workplace-install-v1' > "$work/new/.managed"
(cd "$work/new" && cksum bin/config-workplace lib/cli.sh lib/setup.sh modules/initial-dev.sh lib/dev-tools.sh lib/dev-safety.sh lib/pnpm-metadata.js lib/vscode.sh platforms/dev-install.sh lib/vscode-settings.js manifests/vscode-extensions.txt manifests/vscode-settings.json modules/terminal.sh lib/terminal-detect.sh lib/terminal-files.sh platforms/terminal-install.sh manifests/terminal/zshrc manifests/terminal/plugins.txt) > "$work/new/.checksums"
cat > "$work/entry" <<'WRAPPER'
#!/bin/bash
# config-workplace permanent launcher v1
set -eu
base=$(CDPATH= cd -- "$(dirname -- "$0")/../share/config-workplace" && pwd -P)
exec /bin/bash "$base/bin/config-workplace" "$@"
WRAPPER
chmod 755 "$work/entry"
validate() {
    /bin/bash "$1" --help >/dev/null &&
    /bin/bash "$1" --version >/dev/null &&
    /bin/bash "$1" list >/dev/null
}
validate "$work/new/bin/config-workplace" || fail 'A CLI preparada falhou na validação.'
if [ -e "$target" ] || [ -L "$target" ]; then
    # Even managed directories may contain user files: retain the old payload.
    printf 'Instalação existente será substituída e preservada em backup: %s\n' "$target"
    known=1
    if [ -L "$target" ] || [ ! -d "$target" ] || [ ! -f "$target/.managed" ] || ! cmp -s "$target/.managed" "$work/new/.managed"; then
        known=0
    else
        # Added files, symlinks or local edits require explicit approval too.
        find "$target" -type l > "$work/links"
        find "$target" ! -path "$target" ! -path "$target/bin" ! -path "$target/lib" \
            ! -path "$target/bin/config-workplace" ! -path "$target/lib/cli.sh" \
            ! -path "$target/lib/setup.sh" ! -path "$target/modules" ! -path "$target/modules/initial-dev.sh" \
            ! -path "$target/platforms" ! -path "$target/platforms/dev-install.sh" \
            ! -path "$target/lib/dev-safety.sh" ! -path "$target/lib/pnpm-metadata.js" ! -path "$target/lib/dev-tools.sh" ! -path "$target/lib/vscode.sh" ! -path "$target/lib/vscode-settings.js" \
            ! -path "$target/manifests" ! -path "$target/manifests/vscode-extensions.txt" ! -path "$target/manifests/vscode-settings.json" \
            ! -path "$target/manifests/terminal" ! -path "$target/modules/terminal.sh" ! -path "$target/lib/terminal-detect.sh" ! -path "$target/lib/terminal-files.sh" ! -path "$target/platforms/terminal-install.sh" ! -path "$target/manifests/terminal/zshrc" ! -path "$target/manifests/terminal/plugins.txt" \
            ! -path "$target/.managed" ! -path "$target/.checksums" > "$work/unknown"
        [ ! -s "$work/links" ] && [ ! -s "$work/unknown" ] || known=0
        if ! (cd "$target" && cksum bin/config-workplace lib/cli.sh lib/setup.sh modules/initial-dev.sh lib/dev-tools.sh lib/dev-safety.sh lib/pnpm-metadata.js lib/vscode.sh platforms/dev-install.sh lib/vscode-settings.js manifests/vscode-extensions.txt manifests/vscode-settings.json modules/terminal.sh lib/terminal-detect.sh lib/terminal-files.sh platforms/terminal-install.sh manifests/terminal/zshrc manifests/terminal/plugins.txt) > "$work/current-checksums" 2>/dev/null; then known=0; fi
        cmp -s "$target/.checksums" "$work/current-checksums" || known=0
    fi
    if [ "$known" -eq 0 ]; then
        confirm "Destino desconhecido: substituir $target?" || fail 'Substituição recusada.'
    fi
fi
if [ -e "$entry" ] || [ -L "$entry" ]; then
    if [ -L "$entry" ] || ! cmp -s "$entry" "$work/entry"; then
        confirm "Comando desconhecido: substituir $entry (com backup)?" || fail 'Substituição recusada.'
    fi
fi
if [ -e "$target" ] || [ -L "$target" ]; then mv "$target" "$work/previous"; old_saved=1; fi
mv "$work/new" "$target"; new_live=1
if [ -e "$entry" ] || [ -L "$entry" ]; then mv "$entry" "$work/previous-entry"; entry_saved=1; fi
mv "$work/entry" "$entry"; entry_live=1
validate "$entry" || fail 'Verificação final falhou; restaurando instalação anterior.'
# Retain previous files, including unknown content, instead of deleting them.
backup=
if [ "$old_saved" -eq 1 ] || [ "$entry_saved" -eq 1 ]; then
    backup=$(mktemp -d "$base/share/config-workplace-backup.XXXXXX")
    # Copy before committing so a failed backup still permits rollback.
    if [ "$old_saved" -eq 1 ]; then cp -RP "$work/previous" "$backup/installation"; fi
    if [ "$entry_saved" -eq 1 ]; then cp -P "$work/previous-entry" "$backup/command"; fi
fi
committed=1
printf 'CLI instalada e validada em %s (%s).\n' "$target" "$platform"
[ -z "$backup" ] || printf 'Instalação anterior preservada: %s\n' "$backup"
# PATH configuration is optional and happens only after the install commits.
path_line='export PATH="$HOME/.local/bin:$PATH"'
case ":${PATH:-}:" in
    *":$base/bin:"*) printf '%s\n' 'PATH já configurado; nenhum arquivo alterado.' ;;
    *)
        profile=
        user_shell=${SHELL:-}
        case "${user_shell##*/}" in
            zsh) profile="${ZDOTDIR:-$HOME}/.zprofile" ;;
            bash)
                if [ -f "$HOME/.bash_profile" ]; then profile="$HOME/.bash_profile"
                elif [ -f "$HOME/.bash_login" ]; then profile="$HOME/.bash_login"
                else profile="$HOME/.profile"; fi ;;
        esac
        if [ -n "$profile" ] && [ ! -L "$profile" ] && { [ ! -e "$profile" ] || [ -f "$profile" ]; }; then
            if [ -f "$profile" ] && grep -Fqx "$path_line" "$profile"; then
                printf 'PATH já registrado em %s. Abra uma nova sessão login.\n' "$profile"
            else
                printf 'Alteração proposta: acrescentar ao final de %s:\n%s\n' "$profile" "$path_line"
                if confirm 'Autoriza essa alteração?'; then
                    if [ -f "$profile" ]; then
                        profile_backup=$(mktemp "$profile.config-workplace-backup.XXXXXX")
                        cp -p "$profile" "$profile_backup"
                        printf 'Backup do shell: %s\n' "$profile_backup"
                    fi
                    printf '\n%s\n' "$path_line" >> "$profile"
                    printf '%s\n' 'PATH registrado. Abra uma nova sessão login.'
                fi
            fi
        fi
        printf 'Para usar nesta sessão, execute manualmente:\n%s\n' "$path_line"
        ;;
esac
printf 'Comando: %s\nEstado reservado: %s\n' "$entry" "$base/state/config-workplace"
